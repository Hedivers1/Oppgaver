poeng = 0

# Jeg tror poeng blir : 10
poeng = poeng + 10
print(poeng)

# Jeg tror poeng blir : 35
poeng += 25
print(poeng)

# Jeg tror poeng blir : 30
poeng -= 5
print(poeng)


# Jeg tror poeng blir : 60
poeng *= 2
print(poeng)

# Jeg tror poeng blir : 15.0
poeng /= 4
print(poeng)

## Reflekter og noter:

# Hvilke av forutsigelsene dine stemte? Der du bommet — hva hadde du tenkt feil?
# Jeg fikk riktig, men måtte tenkte meg om to ganger. For på starten kan man tenke at poeng forblir 0. Når det egt endres hver gang. Så jeg måtte tenke meg om to ganger.

# Hva skjedde med datatypen til poeng i det siste steget? Hvorfor?
# Datatypen til poeng ble en float, fordi når man deler et heltall på et annet heltall, blir resultatet et desimaltall.

# Ga utvidelsen samme resultat som +=? Hva er da poenget med +=?
# Ja, utvidelsen ga samme resultat som +=. Poenget med += er at det gjør koden mer lesbar og enklere å skrive. Det er en kortere måte å skrive det på, og det gjør det tydelig at man legger til en verdi til variabelen.
